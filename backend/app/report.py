import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (ListFlowable, ListItem, Paragraph, SimpleDocTemplate,
                                Spacer, Table, TableStyle)


def _p(text, style):
    return Paragraph(escape(str(text or "")), style)


def _bullets(items, style):
    if not items:
        return [_p("None found", style)]
    return [ListFlowable([ListItem(_p(i, style)) for i in items], bulletType="bullet")]


def build_report(filename: str, analysis: dict, model: str | None) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=2 * cm, bottomMargin=2 * cm, title="Meeting report")
    ss = getSampleStyleSheet()
    body, h = ss["BodyText"], ss["Heading2"]
    cell = ParagraphStyle("cell", parent=body, fontSize=9, leading=11)
    small = ParagraphStyle("small", parent=body, fontSize=8, textColor=colors.grey)

    story = [
        Paragraph("Meeting report", ss["Title"]),
        _p(f"Source: {filename}", body),
        _p(f"Generated: {datetime.now():%Y-%m-%d %H:%M}   |   AI model: {model or 'n/a'}", body),
        Spacer(1, 12),
        Paragraph("Summary", h),
        _p(analysis.get("summary"), body),
    ]
    if analysis.get("participants"):
        story.append(_p("Participants: " + ", ".join(analysis["participants"]), body))

    story.append(Paragraph("Decisions", h))
    story += _bullets(analysis.get("decisions") or [], body)

    story.append(Paragraph("Action items", h))
    items = analysis.get("action_items") or []
    if items:
        data = [[_p("Task", cell), _p("Owner", cell), _p("Deadline", cell)]]
        for i in items:
            data.append([_p(i.get("task"), cell), _p(i.get("owner") or "-", cell),
                         _p(i.get("deadline") or "-", cell)])
        table = Table(data, colWidths=[8 * cm, 4 * cm, 5 * cm], repeatRows=1)
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(table)
    else:
        story.append(_p("None found", body))

    story.append(Paragraph("Concerns", h))
    story += _bullets(analysis.get("concerns") or [], body)

    story.append(Paragraph("Follow-up meeting", h))
    if analysis.get("follow_up_needed"):
        story.append(_p("Yes: " + (analysis.get("follow_up_reason") or ""), body))
    else:
        story.append(_p("Not needed", body))

    story += [Spacer(1, 18),
              _p("Generated by AI Business Operations Agent. AI output can contain mistakes: "
                 "please verify before acting.", small)]
    doc.build(story)
    return buf.getvalue()